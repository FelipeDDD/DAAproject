// Backend defaults and geometry are derived from Tiled, never authored twice.
import fs from 'node:fs';
import { readDoors } from '../src/maps/doors.js';
const rooms={school:'classroom',outside:'outside'};
const definitions=Object.fromEntries(Object.entries(rooms).map(([room,file])=>[room,
  readDoors(JSON.parse(fs.readFileSync(`public/assets/maps/${file}.tmj`))).map(({id,x,y,width,height,open,locked,interactive})=>({id,x,y,width,height,open,locked,interactive}))]));
fs.writeFileSync('convex/doorDefinitions.js','// Generated by scripts/sync-door-definitions.mjs from Tiled.\nexport default '+JSON.stringify(definitions,null,2)+';\n');
