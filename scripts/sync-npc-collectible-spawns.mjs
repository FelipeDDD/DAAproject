import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { readNamedMapMarker } from '../src/maps/namedMapMarkers.js';
import { CIGARETTE_PACKS } from '../src/npc/cigarettePacks.js';

const directory = new URL('../public/assets/maps/', import.meta.url);
const spawns = [], ids = new Set();
for (const file of readdirSync(directory).filter(file => file.endsWith('.tmj')).sort()) {
  const source = JSON.parse(readFileSync(new URL(file, directory), 'utf8'));
  const room=file==='classroom.tmj'?'school':file.slice(0,-4);
  const names = [];
  const visit = layers => { for (const layer of layers ?? []) {
    for (const object of layer.objects ?? []) {
      const name=String(object.name??'').toLowerCase();
      const pack=CIGARETTE_PACKS.find(pack=>pack.room===room&&pack.markerNames.includes(name));
      if (/^cigarette-spawn-/i.test(name)||pack) names.push({name:object.name,packId:pack?.packId});
    }
    visit(layer.layers);
  }};
  visit(source.layers);
  for (const entry of names) {
    const {name}=entry;
    const marker = readNamedMapMarker(source, name);
    if (!marker) continue;
    if (!marker.point || !Number.isFinite(marker.x) || !Number.isFinite(marker.y)) throw new Error(`Use a Tiled point for ${name}.`);
    const id = name.toLowerCase();
    if (ids.has(id)) throw new Error(`Duplicate cigarette spawn ID ${id}; use globally unique names.`);
    ids.add(id);
    const packId=entry.packId??marker.properties.packId;
    if(packId&&!CIGARETTE_PACKS.some(pack=>pack.packId===packId))throw new Error(`Invalid packId for ${name}.`);
    spawns.push({id,room,markerName:name,x:marker.x,y:marker.y,...(packId?{packId}:{})});
  }
}
writeFileSync(new URL('../convex/npcCollectibleSpawns.generated.js', import.meta.url),
  '// Generated by scripts/sync-npc-collectible-spawns.mjs from Tiled.\nexport const CIGARETTE_SPAWNS = '
  + JSON.stringify(spawns, null, 2) + ';\n');
console.log(`${spawns.length} cigarette spawn markers synchronized.`);
